import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

// Writes js/asset-manifest.js: every image and sound the game can request, with its real size on disk, so the
// loading bar (js/preloader.js) can weigh its progress by bytes. Image URLs are written exactly as the game
// requests them, query string included (robotics-frame.svg?v=4), or the preloaded copy would not be reused.
// Usage: node tools/build-manifest.mjs (build.mjs runs it).
const root = fileURLToPath(new URL('..', import.meta.url))
const read = (file) => readFileSync(join(root, file), 'utf8')
const walk = (dir) => readdirSync(join(root, dir), { withFileTypes: true })
  .flatMap((entry) => (entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)]))
const code = [read('index.html'), read('js/game-audio.js'), read('js/meera-intro.js'), ...readdirSync(join(root, 'css')).map((f) => read(`css/${f}`))].join('\n')

const images = []
for (const file of walk('assets')) {
  if (!/\.(webp|svg|png|jpe?g)$/.test(file)) continue
  const path = relative(root, file).split('\\').join('/')
  const size = statSync(join(root, file)).size
  // Query-string variants the code uses for this file (for example ?v=4). Without one, the plain path.
  const variants = [...new Set([...code.matchAll(new RegExp(`${path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(\\?[^"')\`\\s]*)`, 'g'))].map((m) => m[1]))]
  const plain = new RegExp(`${path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?!\\?)`).test(code) || !variants.length
  if (plain) images.push([`./${path}`, size])
  for (const query of variants) images.push([`./${path}${query}`, size])
}

// Sounds: one Ogg Opus wrapper per clip (audio/embedded/<id>.ogg.js), fetched by the loading bar and decoded by js/game-audio.js.
const audio = readdirSync(join(root, 'audio/embedded'))
  .filter((name) => name.endsWith('.ogg.js'))
  .sort()
  .map((name) => [`./audio/embedded/${name}`, statSync(join(root, 'audio/embedded', name)).size])

const out = `// Generated by tools/build-manifest.mjs from the files on disk. Do not edit by hand.
window.FactoryAssetManifest = ${JSON.stringify({ images, audio })};
`
writeFileSync(join(root, 'js/asset-manifest.js'), out)
const kb = (n) => `${Math.round(n / 1024)} KB`
console.log(`Manifest: ${images.length} images (${kb(images.reduce((s, x) => s + x[1], 0))}), ${audio.length} sounds (${kb(audio.reduce((s, x) => s + x[1], 0))}).`)
